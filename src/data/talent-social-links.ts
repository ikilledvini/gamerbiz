function normalizeKey(value: string) {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-zA-Z0-9]/g, "")
    .toLowerCase();
}

const NORMALIZED_LINKS = new Map<string, TalentSocialLinks>(
  Object.entries(TALENT_SOCIAL_LINKS).map(([name, links]) => [normalizeKey(name), links]),
);

/** Busca os links manuais por nome artístico, slug ou @username. */
export function getTalentSocialLinks(
  ...candidates: (string | null | undefined)[]
): TalentSocialLinks | null {
  for (const candidate of candidates) {
    if (!candidate) continue;
    const found = NORMALIZED_LINKS.get(normalizeKey(candidate));
    if (found) return found;
  }
  return null;
}
